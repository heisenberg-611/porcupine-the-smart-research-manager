-- ── Row level security ─────────────────────────────────────────────────────
--
-- Readable by any member, writable only by the roles that can change what the
-- review asserts. These numbers go into a published figure: a contributor
-- screening papers has no reason to edit them, and an observer certainly does
-- not.
--
-- No DELETE policy. Clearing a number is setting it back to null, which is an
-- update; removing the row would lose `updated_by` and leave no record that
-- anybody ever entered anything.

alter table public.prisma_manual_counts enable row level security;
alter table public.prisma_manual_counts force row level security;

create policy prisma_manual_counts_select_member on public.prisma_manual_counts
  for select
  using (public.is_project_member(project_id));

create policy prisma_manual_counts_insert_admin on public.prisma_manual_counts
  for insert
  with check (
    public.has_project_role(project_id, array['OWNER','ADMIN']::"AccessRole"[])
    and updated_by = public.current_user_id()
  );

create policy prisma_manual_counts_update_admin on public.prisma_manual_counts
  for update
  using (public.has_project_role(project_id, array['OWNER','ADMIN']::"AccessRole"[]))
  with check (
    public.has_project_role(project_id, array['OWNER','ADMIN']::"AccessRole"[])
    and updated_by = public.current_user_id()
  );

