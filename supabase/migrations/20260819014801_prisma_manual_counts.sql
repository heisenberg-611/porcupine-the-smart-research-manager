-- The PRISMA 2020 numbers this application cannot count.
--
-- The flow diagram has boxes for things no instrumentation here would know:
-- how many records an automation tool marked ineligible, how many reports were
-- sought from a library and never arrived, how many studies were found by
-- chasing citations rather than by searching. Those happen outside the app.
--
-- They are still required. A diagram with those boxes blank is not submittable
-- to a journal; a diagram with them silently zeroed asserts that no report
-- failed retrieval, which is a claim nobody checked. So they are entered by a
-- person, stored here, and drawn in the same figure as the counted ones — with
-- the page saying which is which, and this table recording who last said so.
--
-- Every column is NULLABLE and that is the design. Null means "we have not
-- said" and renders as a dash; zero means "we checked, and it was none".
-- Collapsing the two is precisely the error this table exists to prevent.
-- ═══════════════════════════════════════════════════════════════════════════

