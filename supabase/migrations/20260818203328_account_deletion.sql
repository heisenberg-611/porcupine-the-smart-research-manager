-- ═══════════════════════════════════════════════════════════════════════════
-- A project must keep an owner.
--
-- Nothing stopped the last one leaving. `removeMember` sets `removed_at` with
-- no check, RLS only gates the statement to OWNER or ADMIN, and `updateMemberRole`
-- can demote an owner the same way — so an admin could orphan a project, and
-- account deletion would have done it by accident on every sole-owned project
-- somebody closed their account on.
--
-- In the database rather than in the action, because there are two code paths
-- into it today (removal and demotion) and the deletion flow would have been a
-- third. A rule enforced in three places is a rule enforced in two of them.
--
-- The check runs only when the row was an OWNER and has stopped being one, so
-- it costs nothing on the ordinary update — touching a contributor's digest
-- cadence does not count owners.
-- ═══════════════════════════════════════════════════════════════════════════

create or replace function public.enforce_project_keeps_an_owner()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  -- Was an active owner, and is no longer one.
  if not (OLD.access_role = 'OWNER' and OLD.removed_at is null) then
    return NEW;
  end if;
  if NEW.access_role = 'OWNER' and NEW.removed_at is null then
    return NEW;
  end if;

  if not exists (
    select 1 from public.project_members pm
    where pm.project_id = OLD.project_id
      and pm.id <> OLD.id
      and pm.access_role = 'OWNER'
      and pm.removed_at is null
  ) then
    raise exception
      'This project would be left with no owner. Make somebody else an owner first.'
      using errcode = 'check_violation';
  end if;

  return NEW;
end;
$$;

comment on function public.enforce_project_keeps_an_owner() is
  'Refuses the removal or demotion of a project''s last remaining owner.';

revoke execute on function public.enforce_project_keeps_an_owner() from public;

create trigger project_members_keep_an_owner
  before update on public.project_members
  for each row execute function public.enforce_project_keeps_an_owner();

-- DELETE as well as UPDATE. `removeMember` soft-removes, but the table has a
-- delete policy for admins and nothing above would have covered it.
create or replace function public.enforce_project_keeps_an_owner_on_delete()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if not (OLD.access_role = 'OWNER' and OLD.removed_at is null) then
    return OLD;
  end if;

  -- The project going away takes its members with it, and that is not a
  -- project left without an owner. Without this check a cascade from
  -- `delete from projects` would raise instead.
  if not exists (select 1 from public.projects p where p.id = OLD.project_id) then
    return OLD;
  end if;

  if not exists (
    select 1 from public.project_members pm
    where pm.project_id = OLD.project_id
      and pm.id <> OLD.id
      and pm.access_role = 'OWNER'
      and pm.removed_at is null
  ) then
    raise exception
      'This project would be left with no owner. Make somebody else an owner first.'
      using errcode = 'check_violation';
  end if;

  return OLD;
end;
$$;

revoke execute on function public.enforce_project_keeps_an_owner_on_delete() from public;

create trigger project_members_keep_an_owner_on_delete
  before delete on public.project_members
  for each row execute function public.enforce_project_keeps_an_owner_on_delete();
