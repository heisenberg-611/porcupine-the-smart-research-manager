-- Account deletion.
--
-- ─ Why the row survives ────────────────────────────────────────────────────
--
-- `screening_decisions.decided_by` references this table, and "who excluded
-- these forty papers, and when" has to keep having an answer a year later.
-- That single sentence is the argument for the whole product being defensible,
-- so deletion anonymises the row instead of removing it: email, display name,
-- avatar, ORCID, affiliation and every key column are scrubbed, and the
-- decisions keep pointing at a row that no longer identifies anybody.
--
-- It is pseudonymisation, not erasure, and /dpa says so in those words.
--
-- ─ The ten foreign keys ────────────────────────────────────────────────────
--
-- Ten columns held a user id with NO foreign key at all: annotations.author_id,
-- extractions.extractor_id and .verified_by, project_works.added_by and
-- .assignee_id, projects.created_by, project_keys.wrapped_by,
-- project_members.invited_by, file_objects.owner_id, saved_searches.created_by.
--
-- That is worse than a missing constraint usually is. A `delete from users`
-- did not FAIL on these — it succeeded, and left ten columns pointing at a row
-- that no longer existed. Nothing would have reported it. The screens that
-- join through them would simply have started returning nothing, which reads
-- as "no annotations yet" rather than as corruption.
--
-- RESTRICT where the column is required, SET NULL where it is optional. The
-- point of adding them now is not this migration — the deletion path here
-- never deletes the row — it is the next person who reaches for DELETE and is
-- stopped by the database rather than by a code review.
-- ═══════════════════════════════════════════════════════════════════════════

